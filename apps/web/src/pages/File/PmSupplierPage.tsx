import { useRef, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  Box,
  LookupDialog,
  LookupField,
  TextInput,
  useScanFeedback,
  type LookupColumn,
} from '@cims/ui';
import { useLazyGetCountriesQuery, useLazyGetCountryQuery } from '../../services/masterDataApi';
import {
  useLazyGetPmSupplierQuery,
  useLazyGetPmSuppliersQuery,
  useSavePmSupplierMutation,
  type PmSupplier,
} from '../../services/supplierApi';
import type { ApiQueryError } from '../../services/axiosBaseQuery';
import { PATHS } from '../../routes/paths';
import { COUNTRY_COLUMNS } from './masterColumns';
import {
  COMMON_MESSAGES,
  saveFailureText,
  useEntryFlags,
  type EntryMessages,
  type EntryOption,
} from './masterEntry';
import { MasterEntryShell } from './MasterEntryShell';
import { SectionBox } from './SectionBox';
import { PM_SUPPLIER_COLUMNS } from './supplierColumns';

/** Legacy texts of AppJs/PMSupplier.js, word for word. */
const ENTER_NAME = 'Enter Supplier Name';
const MESSAGES: EntryMessages = {
  // New never checks the code (the server generates it), so this one is only used for a server 409.
  alreadyExists: 'Supplier Code Already Exist',
  doesNotExist: 'Supplier Code not Exist',
  checkFailed: 'Error Loading Supplier Data',
};
const COUNTRY_FAILED = 'Error Loading Country Details';

interface PmSupplierForm {
  code: string;
  name: string;
  address1: string;
  address2: string;
  address3: string;
  address4: string;
  contact1: string;
  contact2: string;
  contact3: string;
  tel: string;
  fax: string;
  email: string;
}

const EMPTY_FORM: PmSupplierForm = {
  code: '',
  name: '',
  address1: '',
  address2: '',
  address3: '',
  address4: '',
  contact1: '',
  contact2: '',
  contact3: '',
  tel: '',
  fax: '',
  email: '',
};

interface ListDialogState {
  title: string;
  columns: readonly LookupColumn[];
  rows: readonly object[];
  onPick: (row: object) => void;
}

/**
 * PM Suppliers Master Details (legacy /File/PmSupplier, CloudMenu 100.16). Same field order, labels, element ids
 * (SupplierCode, btnSupplierCode, CountryCode, btnCountryCode, CountryName), messages and flow as
 * Views/File/PmSupplier.cshtml + AppJs/PMSupplier.js; write-up in the legacy repo docs/16-wave1-masterdata-b.md. The
 * supplier code is generated by the server on a New save. The legacy page has no "pre-entered" box and shows the code's
 * search button only outside New.
 */
export function PmSupplierPage() {
  const navigate = useNavigate();
  const feedback = useScanFeedback();
  const flags = useEntryFlags();
  const { option, optionRef, allowChange, setAllowChange, saveEnabled, setSaveEnabled } = flags;

  const [form, setForm] = useState<PmSupplierForm>(EMPTY_FORM);
  const [countryCode, setCountryCode] = useState('');
  const [countryName, setCountryName] = useState('');
  const [dialog, setDialog] = useState<ListDialogState | null>(null);
  const [busy, setBusy] = useState(false);

  const [loadList] = useLazyGetPmSuppliersQuery();
  const [loadSupplier] = useLazyGetPmSupplierQuery();
  const [loadCountries] = useLazyGetCountriesQuery();
  const [loadCountry] = useLazyGetCountryQuery();
  const [savePmSupplier] = useSavePmSupplierMutation();

  const set = (key: keyof PmSupplierForm, value: string) =>
    setForm((f) => ({ ...f, [key]: value }));

  // Enter commits the typed code and then asks for its record in the same event, before React re-renders: keep the latest
  // code in a ref so the Enter handler does not see the previous (empty) one.
  const codeRef = useRef('');
  const setCode = (value: string) => {
    codeRef.current = value;
    set('code', value);
  };

  /**
   * Legacy `btnNewClick`. It left Country Code and Country Name filled; this clears them too, and AllowChange is reset
   * (the legacy page kept a viewed record locked).
   */
  const clearForm = () => {
    setForm(EMPTY_FORM);
    codeRef.current = '';
    setCountryCode('');
    setCountryName('');
    setAllowChange(true);
    setSaveEnabled(true);
  };

  const changeOption = (next: EntryOption) => {
    flags.setOption(next);
    clearForm();
    if (next === 'View') setSaveEnabled(false);
  };

  /** Legacy `CountryCode.subscribe`: the country name. An unknown or empty code clears the name (legacy left the old one). */
  const loadCountryName = async (code: string) => {
    if (code.length === 0) {
      setCountryName('');
      return;
    }
    const result = await loadCountry(code);
    if (result.data) {
      setCountryName(result.data.countryName);
    } else if ((result.error as ApiQueryError | undefined)?.status === 404) {
      setCountryName('');
    } else {
      feedback.notifyError(COUNTRY_FAILED);
    }
  };

  /** Legacy `LoadSupplierData`: fills the form; View locks the fields. */
  const applyRecord = (s: PmSupplier) => {
    setForm((f) => ({
      ...f,
      name: s.pmSupplierName,
      address1: s.pmSupplierAddress1,
      address2: s.pmSupplierAddress2,
      address3: s.pmSupplierAddress3,
      address4: s.pmSupplierAddress4,
      contact1: s.pmSupplierContact1,
      contact2: s.pmSupplierContact2,
      contact3: s.pmSupplierContact3,
      tel: s.pmSupplierTel,
      fax: s.pmSupplierFax,
      email: s.pmSupplierEmail,
    }));
    setCountryCode(s.countryCode ?? '');
    void loadCountryName(s.countryCode ?? '');
    if (optionRef.current === 'View') setAllowChange(false);
  };

  const loadRecord = async (code: string, notFoundMessage?: string) => {
    setBusy(true);
    try {
      const result = await loadSupplier(code);
      if (result.data) {
        applyRecord(result.data);
      } else if (result.error && (result.error as ApiQueryError).status !== 404) {
        feedback.notifyError(MESSAGES.checkFailed);
      } else if (notFoundMessage) {
        feedback.notifyError(notFoundMessage);
      }
    } finally {
      setBusy(false);
    }
  };

  /** Legacy `SupplierCode.subscribe`: outside New, a code unlocks the form and loads its record. */
  const commitCode = (next: string) => {
    setCode(next);
    if (optionRef.current !== 'New' && next.length > 0) {
      setAllowChange(true);
      void loadRecord(next);
    }
  };

  const openDialog = async (
    title: string,
    columns: readonly LookupColumn[],
    fetchRows: () => Promise<readonly object[] | undefined>,
    onPick: (row: object) => void,
  ) => {
    setBusy(true);
    try {
      const rows = await fetchRows();
      if (!rows) {
        feedback.notifyError(COMMON_MESSAGES.noServer);
      } else if (rows.length === 0) {
        feedback.notifyError(COMMON_MESSAGES.nothingToList);
      } else {
        setDialog({
          title,
          columns,
          rows,
          onPick: (row) => {
            setDialog(null);
            onPick(row);
          },
        });
      }
    } finally {
      setBusy(false);
    }
  };

  /** Legacy `btnSupplierList`: "Supplier Listing"; Select fills the form outside New (in New it only closes). */
  const openSupplierList = () =>
    openDialog(
      'Supplier Listing',
      PM_SUPPLIER_COLUMNS,
      async () => (await loadList()).data,
      (row) => {
        if (optionRef.current === 'New') return;
        const picked = (row as { pmSupplierCode: string }).pmSupplierCode;
        setCode(picked);
        setAllowChange(true);
        void loadRecord(picked);
      },
    );

  /** Legacy `btnCountryCodeList`: "Country Listing"; Select fills the country in every option. */
  const openCountryList = () =>
    openDialog(
      'Country Listing',
      COUNTRY_COLUMNS,
      async () => (await loadCountries()).data,
      (row) => {
        const picked = (row as { countryCode: string }).countryCode;
        setCountryCode(picked);
        void loadCountryName(picked);
      },
    );

  /**
   * Legacy `findSupplierCode` (Enter in the code field). The legacy handler asked the SUPPLIER table (getSupplierData)
   * and tried to copy a column that table does not have, so Enter either said "Invalid Code" or emptied the field; here it
   * looks the code up in the PM suppliers.
   */
  const findCode = () => {
    if (codeRef.current === '') {
      void openSupplierList();
    } else {
      void loadRecord(codeRef.current, COMMON_MESSAGES.invalidCode);
    }
  };

  /** Legacy `beforeSaveCheking` + `chkSupplierCode` + `btnSaveData`. */
  const save = async () => {
    setSaveEnabled(false);
    if (form.name.length <= 0) {
      feedback.notifyError(ENTER_NAME);
      setSaveEnabled(true);
      return;
    }

    // Legacy had no "Enter Supplier Code" check: an empty code simply did not exist.
    if (option !== 'New' && form.code.length === 0) {
      feedback.notifyError(MESSAGES.doesNotExist);
      setSaveEnabled(true);
      return;
    }

    setBusy(true);
    try {
      if (option !== 'New') {
        const check = await loadSupplier(form.code);
        if (!check.data) {
          const status = (check.error as ApiQueryError | undefined)?.status;
          feedback.notifyError(status === 404 ? MESSAGES.doesNotExist : MESSAGES.checkFailed);
          setSaveEnabled(true);
          return;
        }
      }

      const result = await savePmSupplier({
        mode: option === 'New' ? 'New' : 'Change',
        pmSupplierCode: form.code,
        pmSupplierName: form.name,
        pmSupplierAddress1: form.address1,
        pmSupplierAddress2: form.address2,
        pmSupplierAddress3: form.address3,
        pmSupplierAddress4: form.address4,
        pmSupplierContact1: form.contact1,
        pmSupplierContact2: form.contact2,
        pmSupplierContact3: form.contact3,
        pmSupplierTel: form.tel,
        pmSupplierEmail: form.email,
        pmSupplierFax: form.fax,
        countryCode,
      });
      if ('data' in result && result.data) {
        if (option === 'New') setCode(result.data.pmSupplierCode);
        // Like legacy, Save stays disabled until New (or another Option) is chosen.
        feedback.notifySuccess(COMMON_MESSAGES.saved);
      } else if ('error' in result) {
        feedback.notifyError(saveFailureText(result.error as ApiQueryError, MESSAGES));
        setSaveEnabled(true);
      }
    } finally {
      setBusy(false);
    }
  };

  const text = (label: string, key: keyof PmSupplierForm) => (
    <TextInput
      label={label}
      value={form[key]}
      readOnly={!allowChange}
      onChange={(value) => set(key, value)}
    />
  );

  return (
    <>
      <MasterEntryShell
        title="PM Suppliers Master Details"
        option={option}
        onOptionChange={changeOption}
        saveEnabled={saveEnabled}
        onSave={() => void save()}
        onNew={clearForm}
        onClose={() => void navigate(PATHS.home)}
        busy={busy}
      >
        <Box sx={{ display: 'flex', gap: 2, flexWrap: 'wrap' }}>
          <Box sx={{ width: 240 }}>
            <LookupField
              id="SupplierCode"
              searchId="btnSupplierCode"
              label="Supplier Code"
              value={form.code}
              readOnly={!allowChange || option === 'New'}
              searchDisabled={!allowChange}
              hideSearch={option === 'New'}
              onCommit={commitCode}
              onEnter={findCode}
              onSearch={() => void openSupplierList()}
            />
          </Box>
          <Box sx={{ flex: 1, minWidth: 280 }}>
            <TextInput
              label="Supplier Name"
              value={form.name}
              readOnly={!allowChange}
              onChange={(value) => set('name', value)}
            />
          </Box>
        </Box>
        <Box
          sx={{
            display: 'grid',
            gap: 2,
            gridTemplateColumns: { xs: '1fr', md: '1fr 1fr' },
            alignItems: 'start',
          }}
        >
          <SectionBox title="Address Details">
            <Box sx={{ display: 'flex', gap: 2, flexWrap: 'wrap' }}>
              <Box sx={{ width: 220 }}>
                <LookupField
                  id="CountryCode"
                  searchId="btnCountryCode"
                  label="Country"
                  value={countryCode}
                  readOnly
                  onSearch={() => void openCountryList()}
                />
              </Box>
              <Box sx={{ flex: 1, minWidth: 180 }}>
                <TextInput id="CountryName" ariaLabel="Country Name" value={countryName} />
              </Box>
            </Box>
            {text('Address Line1', 'address1')}
            {text('Address Line2', 'address2')}
            {text('Address Line3', 'address3')}
            {text('Address Line4', 'address4')}
          </SectionBox>
          <SectionBox title="Contact Number Details">
            {text('Telephone No', 'tel')}
            {text('Fax No', 'fax')}
            {text('Email Address', 'email')}
          </SectionBox>
          <SectionBox title="Contact Person Details">
            {text('Contact Person 1', 'contact1')}
            {text('Contact Person 2', 'contact2')}
            {text('Contact Person 3', 'contact3')}
          </SectionBox>
        </Box>
      </MasterEntryShell>
      {dialog ? (
        <LookupDialog
          open
          title={dialog.title}
          columns={dialog.columns}
          rows={dialog.rows}
          onSelect={dialog.onPick}
          onClose={() => setDialog(null)}
        />
      ) : null}
    </>
  );
}
